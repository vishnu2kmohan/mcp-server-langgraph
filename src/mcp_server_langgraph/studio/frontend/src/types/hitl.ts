/**
 * Option in a multiple-choice clarification request
 */
export interface ClarificationOption {
  id: string;
  label: string;
  description?: string;
  is_recommended?: boolean;
}

// =============================================================================
// Agent Request Types (What the agent asks for)
// =============================================================================

/**
 * Approval request from an agent requiring human decision
 */
export interface AgentApprovalRequest {
  request_id: string;
  session_id: string;
  task_id: string;
  agent_name: string;
  confidence: number;
  threshold: number;
  proposed_action: string;
  trigger_reason: string;
  context: {
    tokens_used?: number;
    time_elapsed_seconds?: number;
    artifacts?: string[];
    [key: string]: unknown;
  };
  requested_at: string;
  /** AI-generated explanation for HITL dialog (Phase 1 AI-Native Enhancement) */
  ai_explanation?: AIExplanation;
}

/**
 * Clarification request from an agent requiring human input
 */
export interface AgentClarificationRequest {
  request_id: string;
  session_id: string;
  task_id: string;
  agent_name: string;
  clarification_type: "text" | "choice" | "confirmation";
  question: string;
  options: ClarificationOption[];
  placeholder: string | null;
  required: boolean;
  context: Record<string, unknown>;
  requested_at: string;
}

// =============================================================================
// Response Types (What the user sends back)
// =============================================================================

/**
 * UI-layer clarification response (used by ClarificationDialog component)
 *
 * This format is optimized for the dialog UI:
 * - Uses `value` for text input
 * - Uses `selected_option_id` for choice
 * - Includes `responded_by` for attribution
 */
export interface ClarificationUIResponse {
  request_id: string;
  value?: string;
  selected_option_id?: string;
  confirmed?: boolean;
  responded_by: string;
}

/**
 * API-layer clarification response (used by useHITLDialogs hook for API calls)
 *
 * This format matches the backend API contract:
 * - Explicit `response_type` discriminator
 * - Uses `text_response` for text input
 * - Uses `selected_option` for choice
 */
export interface ClarificationAPIResponse {
  request_id: string;
  response_type: "choice" | "text" | "confirm";
  selected_option?: string;
  text_response?: string;
  confirmed?: boolean;
}

/**
 * Approval response from user
 */
export interface ApprovalResponse {
  request_id: string;
  approved: boolean;
  approved_by: string;
  reason?: string;
  modifications?: Record<string, unknown>;
}

