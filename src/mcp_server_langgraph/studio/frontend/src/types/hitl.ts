/**
 * HITL (Human-in-the-Loop) Type Definitions
 *
 * Consolidated types for agent approval and clarification flows.
 * These types are used across:
 * - WebSocket payloads (useAgentRequestWebSocket)
 * - UI components (AgentApprovalDialog, ClarificationDialog)
 * - State management hooks (useHITLDialogs)
 *
 * Type naming convention:
 * - *Request: Data describing what the agent is asking for
 * - *Response: Data the user sends back
 * - *Payload: WebSocket message data
 * - UI suffix: Types used in UI layer
 * - API suffix: Types used in API/hook layer
 */

// =============================================================================
// AI Explanation Types (AI-Native HITL Enhancements Phase 1)
// =============================================================================

/**
 * Individual factor contributing to confidence score.
 *
 * Represents a single piece of evidence that either increases or
 * decreases the agent's confidence in its proposed action.
 */
export interface ConfidenceFactor {
  /** Factor name (e.g., "ambiguous_input", "multiple_interpretations") */
  factor: string;
  /** Impact on confidence (-1.0 to 1.0, negative reduces confidence) */
  weight: number;
  /** Supporting evidence or reasoning for this factor */
  evidence: string;
}

/**
 * Safer alternative action the agent could take.
 *
 * Represents an alternative approach with expected confidence and
 * trade-offs, helping users make informed decisions.
 */
export interface AlternativeSuggestion {
  /** Description of the alternative action */
  action: string;
  /** Expected confidence if this action is taken (0.0 to 1.0) */
  confidence: number;
  /** What the user gives up by choosing this alternative */
  trade_off: string;
}

/**
 * AI-generated explanation for HITL approval requests.
 *
 * Provides rich, context-aware explanations generated by the
 * ExplanationOrchestrator using parallel analysis agents.
 *
 * Core Explanation:
 *   - why_uncertain: Natural language explanation of uncertainty
 *   - what_could_go_wrong: Risk analysis of potential issues
 *   - safer_alternatives: List of safer options with trade-offs
 *
 * Supporting Evidence:
 *   - confidence_factors: Factors affecting confidence score
 *   - reasoning_trace: Key steps in the agent's reasoning
 *
 * Metadata:
 *   - model_used: LLM model that generated the explanation
 *   - generated_at: Timestamp of generation
 *   - generation_latency_ms: Time taken to generate
 *   - cached: Whether explanation was retrieved from cache
 */
export interface AIExplanation {
  /** Natural language explanation of why the agent is uncertain */
  why_uncertain: string;
  /** Risk analysis of potential negative outcomes */
  what_could_go_wrong: string;
  /** List of safer alternative actions (optional) */
  safer_alternatives?: AlternativeSuggestion[];
  /** Factors affecting the confidence score (optional) */
  confidence_factors?: ConfidenceFactor[];
  /** Key steps in the agent's reasoning process (optional) */
  reasoning_trace?: string[];
  /** LLM model used to generate the explanation (optional) */
  model_used?: string;
  /** Timestamp when explanation was generated (optional) */
  generated_at?: string;
  /** Time taken to generate explanation in milliseconds (optional) */
  generation_latency_ms?: number;
  /** Whether explanation was retrieved from cache (optional) */
  cached?: boolean;
}

